"""Categorize Task A extrapolation failures (seed 0, with attention) and write
reports/taskA_failures.md.

    python -m seq2seq.scripts.taskA_failures
"""
from collections import Counter

import config


def category(gold, pred):
    g_d, p_d = gold.split(".")[0], pred.split(".")[0] if "." in pred else pred
    gd, pd_ = g_d.replace(",", "").lstrip("$"), p_d.replace(",", "").lstrip("$")
    if gd == pd_ and gold.split(".")[-1] != pred.split(".")[-1]:
        return "cents wrong, dollars right"
    if gd == pd_:
        return "comma placement"
    if len(pd_) < len(gd):
        return "dropped digits (magnitude too small)"
    if len(pd_) > len(gd):
        return "extra digits (magnitude too large)"
    return "right length, wrong digits"


def failures_from_checkpoint():
    """Decode test_out with the saved seed-0 attention model (same data, same vocab)."""
    import json
    import torch
    from seq2seq.common import RUNS
    from seq2seq.data_taskA import make_splits
    from seq2seq.model import Seq2Seq
    from seq2seq.train import greedy_decode
    from seq2seq.vocab import UNK, SymbolVocab
    sp = make_splits(seed=config.SEED)
    sv = SymbolVocab.build([s for s, _, _ in sp["train"]])
    tv = SymbolVocab.build([t for _, t, _ in sp["train"]])
    d = RUNS / f"taskA_att_seed{config.SEEDS[0]}"
    hp = json.loads((d / "run.json").read_text())["hparams"]
    model = Seq2Seq(hp["src_vocab"], hp["tgt_vocab"], emb=hp["emb"], hid=hp["hid"], att=hp["att"],
                    dropout=hp["dropout"], attention=hp["attention"])
    model.load_state_dict(torch.load(d / "model.pt"))
    preds = [tv.decode(p) for p in greedy_decode(model, [sv.encode(s) for s, _, _ in sp["test_out"]], 16)]
    return [{"src": " ".join(s), "gold": "".join(g), "pred": "".join(p), "digits": dg,
             "src_has_unseen_word": any(sv.stoi.get(w, UNK) == UNK for w in s)}
            for (s, g, dg), p in zip(sp["test_out"], preds) if "".join(p) != "".join(g)]


def main():
    fails = failures_from_checkpoint()
    for f in fails:
        f["category"] = category(f["gold"], f["pred"])
    by_digit = {}
    for d in (5, 6, 7):
        c = Counter(f["category"] for f in fails if f["digits"] == d)
        by_digit[d] = c
    cats = sorted({f["category"] for f in fails})
    lines = ["# Task A failures (seed 0, with attention, 5-7 digit amounts)", "",
             "All examples are synthetic (generated by `seq2seq/data_taskA.py`).", "",
             "| Category | " + " | ".join(f"{d} digits" for d in by_digit) + " |",
             "|---|" + "---:|" * len(by_digit)]
    for c in cats:
        lines.append(f"| {c} | " + " | ".join(str(by_digit[d][c]) for d in by_digit) + " |")
    unseen = sum(f["src_has_unseen_word"] for f in fails)
    dollars = lambda x: x.split(".")[0].replace("$", "").replace(",", "")
    lens = Counter(len(dollars(f["pred"])) for f in fails)
    cents_ok = sum(f["pred"].split(".")[-1] == f["gold"].split(".")[-1] for f in fails) / len(fails)
    low3_ok = sum(dollars(f["pred"])[-3:] == dollars(f["gold"])[-3:] for f in fails) / len(fails)
    lines += ["", f"Failures whose source contains a word never seen in training (`million`): {unseen} of {len(fails)}.",
              "", f"Length of the predicted dollar part across all failures: {dict(lens)} digits. "
              f"Cents correct in {cents_ok:.1%} of failures; last three dollar digits correct in {low3_ok:.1%}. "
              "The model reproduces the 4-digit template `$X,XXX.XX` it saw in training and fills it from the "
              "end of the number, dropping the leading digits.",
              "", "## Examples", "", "| Digits | Source | Gold | Predicted | Category |", "|---:|---|---|---|---|"]
    shown = []
    for d in (5, 6, 7):
        shown += [f for f in fails if f["digits"] == d][:2]
    for f in shown[:6]:
        lines.append(f"| {f['digits']} | {f['src']} | `{f['gold']}` | `{f['pred']}` | {f['category']} |")
    (config.REPORTS / "taskA_failures.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
